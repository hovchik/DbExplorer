using DbExplorer.Application;
using DbExplorer.Application.Compare;
using DbExplorer.Application.Lab;
using DbExplorer.Application.Metadata;
using DbExplorer.Core.Connections;
using DbExplorer.Core.Models;
using DbExplorer.Providers.Postgres;
using Npgsql;

namespace DbExplorer.Tests;

/// <summary>
/// The Comparer's migration script against a real PostgreSQL server: two databases that drifted apart (a missing table
/// with a key, changed and extra columns, a changed view, a missing function), the script run in one transaction, and the
/// target then matching the source. Skipped unless DBEXPLORER_TEST_PG is set to "host;port;user;password" of a server
/// where the user may create the databases dbx_migration_src and dbx_migration_dst.
/// </summary>
public sealed class PostgresMigrationIntegrationTests : IAsyncLifetime
{
    private const string Source = "dbx_migration_src";
    private const string Target = "dbx_migration_dst";
    private const string Pg = PostgresProviderFactory.ProviderKey;
    private static readonly string? Settings = Environment.GetEnvironmentVariable("DBEXPLORER_TEST_PG");

    private readonly string _root = Path.Combine(Path.GetTempPath(), "dbx-pg-" + Guid.NewGuid().ToString("N"));
    private MetadataService? _metadata;

    private static ConnectionProfile Profile(string database)
    {
        var p = Settings!.Split(';');
        return new ConnectionProfile
        {
            ProviderKey = Pg, Host = p[0], Port = int.Parse(p[1]), UserName = p[2], Password = p[3], Database = database, Name = database
        };
    }

    public async Task InitializeAsync()
    {
        if (Settings is null) return;
        await using (var admin = new NpgsqlConnection(PostgresSql.BuildConnectionString(Profile("postgres"))))
        {
            await admin.OpenAsync();
            foreach (var db in new[] { Source, Target })
            {
                await Exec(admin, $"DROP DATABASE IF EXISTS {db} WITH (FORCE)");
                await Exec(admin, $"CREATE DATABASE {db}");
            }
        }

        await Exec(Source, """
            CREATE TABLE customers (id integer PRIMARY KEY, name varchar(100) NOT NULL, email text, created_at timestamptz NOT NULL DEFAULT now());
            CREATE TABLE orders (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer NOT NULL REFERENCES customers (id), total numeric(12,2) NOT NULL DEFAULT 0);
            CREATE INDEX ix_orders_customer ON orders (customer_id);
            CREATE TABLE notes (id serial PRIMARY KEY, body text);
            CREATE VIEW big_customers AS SELECT id, name FROM customers WHERE id > 100;
            CREATE VIEW top_big_customers AS SELECT id FROM big_customers WHERE id > 1000;
            CREATE FUNCTION order_count(c integer) RETURNS bigint LANGUAGE sql AS $$ SELECT count(*) FROM orders WHERE customer_id = c $$;
            """);
        await Exec(Target, """
            CREATE TABLE customers (id integer PRIMARY KEY, name varchar(50) NOT NULL, phone text);
            INSERT INTO customers VALUES (1, 'Ann', '555');
            CREATE VIEW big_customers AS SELECT id, name FROM customers WHERE id > 50;
            CREATE TABLE legacy (id integer PRIMARY KEY);
            """);

        _metadata = new MetadataService(new MetadataCache(new AppPaths(_root)), new SchemaHistoryStore(new AppPaths(_root)), new VirtualForeignKeyStore(new AppPaths(_root)));
    }

    public Task DisposeAsync()
    {
        NpgsqlConnection.ClearAllPools();
        try { Directory.Delete(_root, true); } catch { /* best effort */ }
        return Task.CompletedTask;
    }

    private static async Task Exec(NpgsqlConnection cn, string sql)
    {
        await using var cmd = new NpgsqlCommand(sql, cn);
        await cmd.ExecuteNonQueryAsync();
    }

    private static async Task Exec(string database, string sql)
    {
        await using var cn = new NpgsqlConnection(PostgresSql.BuildConnectionString(Profile(database)));
        await cn.OpenAsync();
        await Exec(cn, sql);
    }

    private async Task<MigrationSide> ReadAsync(string database)
    {
        var profile = Profile(database);
        var provider = new PostgresProvider(profile);
        var snapshot = await _metadata!.LoadAsync(profile, provider, forceRefresh: true);
        var constraints = new Dictionary<DbObject, DbTableConstraints>();
        foreach (var table in snapshot.Objects.Where(o => o.Type == DbObjectType.Table))
            constraints[table] = await provider.GetTableConstraintsAsync(table);
        return new MigrationSide(snapshot, Pg, database, constraints);
    }

    private static async Task RunAsync(string script)
    {
        var provider = new PostgresProvider(Profile(Target));
        await using var run = await provider.BeginScriptSessionAsync(null, transactional: true);
        await run.ExecuteAsync(script, 60);
        await run.CommitAsync();
    }

    [SkippableFact]
    public async Task Script_makes_the_target_match_and_a_second_run_finds_nothing_to_do()
    {
        Skip.If(Settings is null);

        var script = MigrationScriptBuilder.Build(await ReadAsync(Source), await ReadAsync(Target));
        Assert.True(script.HasChanges, script.Script);
        Assert.Contains(script.Items, i => i is { Action: MigrationAction.Create, Name: "orders" });
        Assert.Contains(script.Items, i => i is { Action: MigrationAction.Alter, Name: "customers" });
        Assert.Contains(script.Items, i => i is { Action: MigrationAction.Replace, Name: "big_customers" });
        Assert.Contains(script.Items, i => i is { Action: MigrationAction.Create, Name: "order_count" });
        Assert.DoesNotContain(script.Items, i => i.Action == MigrationAction.Manual);
        await RunAsync(script.Script);

        var again = MigrationScriptBuilder.Build(await ReadAsync(Source), await ReadAsync(Target));
        Assert.False(again.HasChanges, again.Script);
        Assert.Contains("-- DROP TABLE \"public\".\"legacy\";", again.Script);

        // The row on the target survived, and its extra column too.
        await using var cn = new NpgsqlConnection(PostgresSql.BuildConnectionString(Profile(Target)));
        await cn.OpenAsync();
        await using var cmd = new NpgsqlCommand("SELECT phone FROM customers WHERE id = 1", cn);
        Assert.Equal("555", await cmd.ExecuteScalarAsync());

        // Dropping what only the target has.
        var drops = MigrationScriptBuilder.Build(await ReadAsync(Source), await ReadAsync(Target), new MigrationOptions { DropExtras = true });
        Assert.Contains(drops.Items, i => i is { Action: MigrationAction.Drop, Name: "legacy" });
        await RunAsync(drops.Script);
        var last = MigrationScriptBuilder.Build(await ReadAsync(Source), await ReadAsync(Target), new MigrationOptions { DropExtras = true });
        Assert.False(last.HasChanges, last.Script);
    }
}
